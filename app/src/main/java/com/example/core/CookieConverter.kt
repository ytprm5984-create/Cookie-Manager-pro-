package com.example.core

import com.example.model.ParsedCookie
import org.json.JSONArray
import org.json.JSONObject

data class ExportResult(
  val content: String,
  val warnings: List<String>
)

object CookieConverter {

  fun toJson(cookies: List<ParsedCookie>, validOnly: Boolean = true): ExportResult {
    val targetCookies = if (validOnly) cookies.filter { it.isValid } else cookies
    val warnings = mutableListOf<String>()

    val jsonArray = JSONArray()
    for (cookie in targetCookies) {
      val obj = JSONObject()
      obj.put("name", cookie.name)
      obj.put("value", cookie.value)
      obj.put("domain", cookie.domain)
      obj.put("path", if (cookie.path.isEmpty()) "/" else cookie.path)
      obj.put("secure", cookie.secure)
      obj.put("httpOnly", cookie.httpOnly)
      obj.put("session", cookie.session)

      if (!cookie.session && cookie.expirationDate != null && cookie.expirationDate > 0) {
        obj.put("expirationDate", cookie.expirationDate)
      }

      cookie.sameSite?.let {
        obj.put("sameSite", it)
      }
      cookie.hostOnly?.let {
        obj.put("hostOnly", it)
      }
      cookie.storeId?.let {
        obj.put("storeId", it)
      }

      jsonArray.put(obj)
    }

    val output = jsonArray.toString(2)
    return ExportResult(content = output, warnings = warnings)
  }

  fun toNetscape(cookies: List<ParsedCookie>, validOnly: Boolean = true): ExportResult {
    val targetCookies = if (validOnly) cookies.filter { it.isValid } else cookies
    val warnings = mutableListOf<String>()

    var countSameSiteIgnored = 0
    val sb = StringBuilder()
    sb.append("# Netscape HTTP Cookie File\n")
    sb.append("# https://curl.se/docs/http-cookies.html\n")
    sb.append("# This file was generated by Cookie Manager Pro\n")
    sb.append("# Developed with 💻 by Sheikh Sojib\n")
    sb.append("# Domain\tIncludeSubdomains\tPath\tSecure\tExpiration\tName\tValue\n\n")

    for (cookie in targetCookies) {
      if (cookie.sameSite != null) {
        countSameSiteIgnored++
      }

      // Domain column: prefix with #HttpOnly_ if httpOnly is true
      val domainPrefix = if (cookie.httpOnly) "#HttpOnly_" else ""
      val rawDomain = cookie.domain
      val domainCol = "$domainPrefix$rawDomain"

      // Include subdomains: TRUE if leading dot or hostOnly == false
      val includeSubdomains = when {
        cookie.hostOnly == true -> "FALSE"
        rawDomain.startsWith(".") -> "TRUE"
        else -> "FALSE"
      }

      val pathCol = if (cookie.path.isEmpty()) "/" else cookie.path
      val secureCol = if (cookie.secure) "TRUE" else "FALSE"

      val expirationCol = if (cookie.session || cookie.expirationDate == null || cookie.expirationDate <= 0) {
        "0"
      } else {
        cookie.expirationDate.toLong().toString()
      }

      val nameCol = cookie.name
      val valueCol = cookie.value

      sb.append("$domainCol\t$includeSubdomains\t$pathCol\t$secureCol\t$expirationCol\t$nameCol\t$valueCol\n")
    }

    if (countSameSiteIgnored > 0) {
      warnings.add(
        "Netscape format does not support the 'SameSite' attribute ($countSameSiteIgnored cookie(s) omitted SameSite property during conversion)."
      )
    }

    return ExportResult(content = sb.toString(), warnings = warnings)
  }
}
